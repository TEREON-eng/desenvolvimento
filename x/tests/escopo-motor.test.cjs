'use strict';
const assert=require('node:assert/strict');
const scope=require('../universo/obras/escopo-motor.js');
let a=scope.add([],{id:'rev',kind:'scope',name:'Revisão elétrica',workId:'obra-1',source:'registered'});
a=scope.add(a,{id:'quadros',kind:'stage',parentId:'rev',name:'Quadros elétricos',workId:'obra-1'});
a=scope.add(a,{id:'qd1',kind:'substage',parentId:'quadros',name:'QD1',workId:'obra-1',source:'promoted'});
a=scope.add(a,{id:'spda',kind:'scope',name:'SPDA',workId:'obra-1'});
a=scope.add(a,{id:'entrada',kind:'scope',name:'Entrada de energia',workId:'obra-1'});
a=scope.add(a,{id:'abrigo',kind:'stage',parentId:'entrada',name:'Abrigo',workId:'obra-1'});
assert.equal(scope.paths(a).find(x=>x.id==='qd1').path,'Revisão elétrica › Quadros elétricos › QD1');
assert.equal(scope.paths(a).find(x=>x.id==='quadros').kind,'stage','etapa-mãe pode ser destino direto');
assert.equal(scope.paths(a).find(x=>x.id==='spda').path,'SPDA','escopo pode existir sem etapas');
assert.throws(()=>scope.add(a,{id:'bad',kind:'substage',parentId:'rev',name:'Errado',workId:'obra-1'}),/Hierarquia inválida/);
assert.throws(()=>scope.add(a,{id:'bad',kind:'stage',parentId:'quadros',name:'Errado'}),/Hierarquia inválida/);
assert.throws(()=>scope.add(a,{id:'bad',kind:'stage',parentId:'rev',name:'Outra obra',workId:'obra-2'}),/obras diferentes/);
const changed=scope.rename(a,'qd1','QD01');
assert.equal(scope.paths(changed).find(x=>x.id==='qd1').path,'Revisão elétrica › Quadros elétricos › QD01');
assert.equal(scope.paths(a).find(x=>x.id==='qd1').name,'QD1','nenhuma mutação da entrada');
const archived=scope.archive(a,'quadros');
assert.equal(scope.paths(archived).find(x=>x.id==='qd1').archived,true);
assert.equal(scope.paths(a).find(x=>x.id==='qd1').archived,false,'arquivamento não altera dados originais');
assert.equal(scope.paths(archived).find(x=>x.id==='spda').archived,false);
console.log('TEREON X: motor independente Escopo > Etapa > Subetapa OK');
