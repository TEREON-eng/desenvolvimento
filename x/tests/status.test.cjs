/* TEREON X — status de conexão e conta sem confundir logout e falha de rede. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const read=p=>fs.readFileSync(path.join(__dirname,'../..',p),'utf8');
const nodes=Object.fromEntries(['xConnection','xAccount','txNetwork'].map(id=>[id,{textContent:'',dataset:{},title:'',setAttribute(key,value){this[key]=value}}]));
const callbacks={};
const win={navigator:{onLine:true},document:{getElementById:id=>nodes[id]},addEventListener:(event,cb)=>{callbacks[event]=cb}};
const context={window:win,globalThis:win};
vm.createContext(context);
new vm.Script(read('x/status.js'),{filename:'x/status.js'}).runInContext(context);
assert.equal(nodes.xConnection.textContent,'Online');
assert.equal(nodes.txNetwork.textContent,'ON','status compacto ao lado do perfil');
assert.equal(nodes.xAccount.textContent,'Verificando conta');
win.TereonXStatus.setAccount('visitor');
assert.equal(nodes.xAccount.textContent,'Visitante');
win.TereonXStatus.setAccount('registered');
assert.equal(nodes.xAccount.textContent,'Registrado');
win.navigator.onLine=false;callbacks.offline();
assert.equal(nodes.xConnection.textContent,'Offline');
assert.equal(nodes.txNetwork.textContent,'OFF','sem rede exibe OFF');
assert.equal(nodes.xAccount.textContent,'Registrado','rede offline não provoca logout');
win.TereonXStatus.setAccount('registered',{unverified:true});
assert.equal(nodes.xAccount.textContent,'Registrado · sessão offline');
win.TereonXStatus.setAccount('unavailable');
assert.equal(nodes.xAccount.textContent,'Conta indisponível');
win.navigator.onLine=true;callbacks.online();
assert.equal(nodes.xConnection.textContent,'Online');
assert.equal(nodes.xAccount.textContent,'Conta indisponível','rede online não presume autenticação');
win.TereonXStatus.setAccount('registered',{unverified:true});
assert.equal(nodes.xAccount.textContent,'Registrado · verificando','sessão local visível enquanto validação remota aguarda');
const auth=read('x/listas/auth.js'),html=read('x/index.html');
assert.ok(auth.includes("setAccount(uid?'registered':'visitor')"));
assert.ok(auth.includes("setAccount(uid?'registered':'unavailable'"));
assert.ok(auth.includes("setAccount('unavailable')"));
assert.ok(html.includes('data-tx-header="main"')&&html.includes('/x/status.js'));
const header=read('x/components/header.js');
assert.ok(header.includes('id="xStatus"')&&header.includes('tx-account-link'));
assert.ok(header.includes('id="txNetwork"')&&header.includes('tx-status-hidden'),'chips redundantes ocultos');
assert.ok(auth.includes("event==='INITIAL_SESSION'")&&auth.includes("session?.user?'registered':'visitor'"),'sessão inicial informa identidade antes de esperar validação remota');
assert.ok(header.includes('tx-header-right')&&header.includes('id="txNetwork"'),'conta e rede agrupadas; retorno na trilha do cabeçalho');
const pwa=read('x/pwa.js');
assert.ok(pwa.includes("const VERSION='x.0.3.24'"),'versão do script PWA coincide com a versão publicada');
assert.ok(pwa.includes('updateInstallVisibility')&&pwa.includes('standalone()'),'Instalar é ocultado quando PWA está instalado');
assert.ok(pwa.includes('(!installPrompt&&!iosSafari())'),'Instalar não fica visível por padrão sem opção de instalação');
console.log('TEREON X: Online/Offline e Visitante/Registrado/Indisponível sem confusão OK');
