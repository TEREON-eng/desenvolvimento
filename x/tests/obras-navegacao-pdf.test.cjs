'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const C=require('../universo/empreiteiros/motor.js');
let state={contractors:[],teams:[]};
state=C.addContractor(state,{id:'js',name:'Empreiteiro JS'});
state=C.addTeam(state,{id:'a',contractorId:'js',name:'Equipe A'});
assert.equal(state.teams[0].contractorId,'js');
assert.throws(()=>C.addTeam(state,{id:'b',name:'Equipe B',contractorId:'inexistente'}),/não encontrado/);
assert.throws(()=>C.removeContractor(state,'js'),/possui equipes/);
let edited=C.rename(state,'team','a','Equipe A1');assert.equal(edited.teams[0].name,'Equipe A1');
assert.equal(state.teams[0].name,'Equipe A','edição imutável');
state=C.removeTeam(state,'a');state=C.removeContractor(state,'js');assert.equal(state.contractors.length,0);
const base=path.resolve(__dirname,'..');
const read=file=>fs.readFileSync(path.join(base,file),'utf8');
const obras=read('universo/obras/lab.html'),contractors=read('universo/empreiteiros/lab.html'),diary=read('universo/diario/lab.html'),diaryJS=read('universo/diario/lab.js'),diaryCSS=read('universo/diario/lab.css'),visits=read('universo/visitas/lab.html');
for(const href of ['../empreiteiros/lab.html','../diario/lab.html','../visitas/lab.html'])assert.ok(obras.includes(href),'navegação de Obras: '+href);
assert.ok(contractors.includes('id="contractor-form"')&&contractors.includes('id="team-form"'),'cadastro por formulários');
assert.ok(visits.includes('Em preparação'),'não sugerir que Visitas foi implementado');
assert.ok(diary.includes('id="print-day"')&&diary.includes('id="print-report"'),'impressão do Diário');
assert.ok(diaryJS.includes('function printDay()')&&diaryJS.includes('window.print()'),'exportação por impressão do navegador');
assert.ok(diaryJS.includes("tereon-x-contractors-simulation-v1")&&diaryJS.includes('importLocalContractors();'),'Diário lê empreiteiros do laboratório local');
assert.ok(diaryJS.includes("execution.latest(reports,e.id,date)"),'PDF indica estado real apontado no dia');
assert.ok(diaryCSS.includes('@media print')&&diaryCSS.includes('size:A4'),'diagramação para PDF');
for(const file of ['universo/empreiteiros/lab.js','universo/diario/lab.js'])new Function(read(file));
assert.ok(!read('universo/empreiteiros/lab.js').includes('createClient('),'simulação local');
console.log('TEREON X: Obras, empreiteiros e PDF de Diário — contratos estáticos e motores OK');
