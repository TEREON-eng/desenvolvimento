/* TEREON X — regressão de módulos sem browser e sem dependências. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const base=path.resolve(__dirname,'../..');
function src(p){return fs.readFileSync(path.join(base,p),'utf8')}
function run(){
 const context={window:{},console,Date,Math};vm.createContext(context);
 for(const file of ['x/listas/store.js','x/listas/servico.js'])new vm.Script(src(file),{filename:file}).runInContext(context);
 return context.window;
}
const root=run(),map=new Map(),storage={getItem:k=>map.has(k)?map.get(k):null,setItem:(k,v)=>map.set(k,v)};
const key=root.TereonXListStore.KEY;
assert.equal(key,'tereon-x-lab-v1','preservar chave localStorage existente');
map.set(key,JSON.stringify({lists:[{id:'antiga',name:'Lista histórica',items:[{id:'old-1',name:'Condutor',qty:'100',unit:'m',stage:'Geral',values:{cor:'Azul'}}],stages:['Geral']}] }));
let sequence=0,uuidSequence=0;
const recordUuid=()=>('00000000-0000-4000-8000-'+String(++uuidSequence).padStart(12,'0'));
const repository=root.TereonXListStore.create({storage}),service=root.TereonXLists.create(repository,{newId:()=>String(++sequence),newRecordUid:recordUuid});
assert.equal(service.get('antiga').recordUid,undefined,'leitura não deve migrar lista antiga silenciosamente');
assert.equal(map.get(key).includes('recordUid'),false,'abrir não regrava dados históricos');
assert.equal(service.snapshot().lists[0].items[0].name,'Condutor');
assert.equal(service.get('antiga').items[0].values.cor,'Azul');
const listId=service.createList('  Obra A  ');
assert.equal(service.get(listId).name,'Obra A');
assert.ok(/^[0-9a-f-]{36}$/.test(service.get(listId).recordUid),'lista nova recebe identidade técnica');
const oldBefore=service.exportList('antiga'),oldUid=service.ensureRecordUid('antiga');
assert.equal(oldUid,service.get('antiga').recordUid,'migração explícita persiste a mesma identidade');
assert.equal(service.ensureRecordUid('antiga'),oldUid,'não deve alterar UID ao repetir');
assert.equal(service.get('antiga').id,oldBefore.id,'ID original preservado');
assert.deepEqual(service.get('antiga').items,oldBefore.items,'lançamentos e dados técnicos intactos');
assert.deepEqual(service.get('antiga').stages,oldBefore.stages,'etapas intactas');
const reloaded=root.TereonXListStore.create({storage}),reloadService=root.TereonXLists.create(reloaded,{newRecordUid:recordUuid});
assert.equal(reloadService.get('antiga').recordUid,oldUid,'identidade sobrevive reabertura');
assert.equal(reloadService.get(listId).recordUid,service.get(listId).recordUid,'lista nova permanece estável');
const item={catalogId:'FT_INFRA-001',name:'Eletrodutos · Rígido',qty:3,unit:'un',stage:'  GERAL  ',values:{'DET-001':'Rígido'},simulacao:true};
const itemId=service.upsertItem(listId,item);
assert.equal(service.get(listId).items.length,1);
assert.equal(service.get(listId).stages[0],'GERAL');
assert.equal(item.stage,'  GERAL  ','módulo não altera entrada');
const stageId=service.upsertItem(listId,{...item,name:'Novo',stage:'geral'},itemId);
assert.equal(stageId,itemId);
assert.equal(service.get(listId).items[0].stage,'GERAL');
assert.equal(service.get(listId).stages.length,1);
const duplicate=service.duplicateItem(listId,itemId);
assert.notEqual(duplicate,itemId);assert.equal(service.get(listId).items.length,2);
service.removeItem(listId,duplicate);
assert.equal(service.get(listId).items.length,1);
assert.equal(service.get('antiga').items.length,1,'registro histórico preservado');
const snapshot=service.exportList(listId);
snapshot.items[0].name='MODIFICADO';
assert.equal(service.get(listId).items[0].name,'Novo','snapshot de exportação não pode alterar lista');
const before=map.get(key);
assert.throws(()=>service.upsertItem(listId,{...item,qty:0}),/Preencha/);
assert.equal(map.get(key),before,'erro de validação não grava');
const broken={getItem:()=>map.get(key),setItem:()=>{throw Error('quota')}};
const brokenStore=root.TereonXListStore.create({storage:broken});
const brokenService=root.TereonXLists.create(brokenStore,{newRecordUid:recordUuid});
assert.throws(()=>brokenService.createList('Falha'),/Alteração cancelada/);
assert.equal(brokenService.snapshot().lists.length,2,'erro de gravação não altera memória');
map.set(key,JSON.stringify({lists:[{id:'legacy2',name:'Legado 2',items:[],stages:[]}]}));
const failingRepo=root.TereonXListStore.create({storage:broken});
const failingService=root.TereonXLists.create(failingRepo,{newRecordUid:recordUuid});
assert.throws(()=>failingService.ensureRecordUid('legacy2'),/Alteração cancelada/);
assert.equal(failingService.get('legacy2').recordUid,undefined,'falha na migração preserva dados em memória');
assert.equal(JSON.parse(map.get(key)).lists[0].recordUid,undefined,'falha na migração preserva dados gravados');
assert.throws(()=>root.TereonXListStore.create({storage:{getItem:()=>'{',setItem(){}}}),/Nenhum dado foi alterado/);

// Adaptador Listas → Relações: consulta não escreve e preparo é explícito.
const adapterContext={};vm.createContext(adapterContext);
new vm.Script(src('x/relacoes/origem-listas.js'),{filename:'x/relacoes/origem-listas.js'}).runInContext(adapterContext);
const adapter=adapterContext.TereonXListRelationsAdapter.create(service);
const reference=adapter.reference('antiga');
assert.equal(reference.type,'list');
assert.equal(reference.originId,'antiga');
assert.equal(reference.recordUid,oldUid);
assert.equal(reference.synchronized,false);
assert.equal(reference.remoteLinkAllowed,false);
assert.throws(()=>adapter.reference('não existe'),/não encontrada/);
const beforePrepare=map.get(key);
const prepared=adapter.prepare('antiga');
assert.equal(prepared.recordUid,oldUid,'não muda identidade existente');
assert.equal(map.get(key),beforePrepare,'preparo repetido não regrava lista existente');

const html=src('x/index.html');
const scripts=[...html.matchAll(/<script src="([^"]+)"/g)].map(x=>x[1].split('?')[0]);
const expected=['/x/listas/store.js','/x/listas/servico.js','/x/motor-compartilhar.js','/x/catalogo/motor.js','/x/catalogo/seletor.js','/x/listas/nuvem/motor.js','/x/listas/integracao.js','/x/listas/app.js','/x/pwa.js'];
assert.deepEqual(scripts,expected,'ordem explícita de dependências');
assert.equal(/<script>/.test(html),false,'shell não deve conter lógica inline');
for(const url of scripts)new vm.Script(src(url.slice(1)),{filename:url});
for(const file of ['x/fichario-x/leitor.js','x/fichario-x/simulador.js','x/motor-compartilhar.js','x/sugestoes-config.js','x/sw.js'])new vm.Script(src(file),{filename:file});
const goldenAdd=src('x/tests/fixtures/modal-adicionar-aprovado-x034.html');
const at=html.indexOf('<dialog id="addDialog"');
assert.ok(at>=0,'modal de Adicionar item deve estar no shell');
const currentAdd=html.slice(at,html.indexOf('</dialog>',at)+9);
assert.equal(currentAdd,goldenAdd,'estrutura do modal deve ser idêntica à aprovada na X.0.3.4');
assert.ok(src('x/styles.css').includes('.tag-tray{')&&src('x/styles.css').includes('.tag.required{'),'tags e contornos aprovados preservados');
assert.ok(src('x/listas/app.js').includes('focus=pickFirstMissing();redrawAdd();'),'remoção de tags retoma primeira obrigatória pendente');
assert.ok(src('x/listas/app.js').includes('lists.upsertItem(activeId,itemData,editId)'),'modal aprovado grava pelo Motor Único de Listas');
const actualPicker=src('x/catalogo/seletor.js');
const listApp=src('x/listas/app.js');
const legacyCloudPage=src('x/listas/nuvem/lab.html');
assert.ok(listApp.includes("if(a.dataset.action==='add')openAdd()"),'Adicionar item usa o modal aprovado X.0.3.4');
assert.ok(listApp.includes("$('addDialog').showModal()"),'fluxo original abre modal de especificação');
assert.ok(actualPicker.includes("showModal()")&&actualPicker.includes("TereonXCatalog.visibleDetails"),'modal técnico mantém características condicionais');
assert.ok(actualPicker.includes("TereonXCatalog.missing")&&actualPicker.includes("TereonXCatalog.technicalName"),'validação e formação do nome técnico preservadas');
assert.ok(legacyCloudPage.includes("location.replace('/x/?view=lists')"),'laboratório legado direciona para Minhas listas com modal técnico');
assert.ok(html.includes('id="listDialog"')&&html.includes('id="listContent"'),'detalhes abrem em dialog independente');
assert.ok(listApp.includes("if(!$('listDialog').open)$('listDialog').showModal()"),'lista abre como modal');
assert.ok(listApp.includes('list-return')&&listApp.includes('← Minhas listas'),'retorno de lista ao conjunto');
assert.ok(listApp.includes("$('listDialog').addEventListener('close'"),'fechamento por ESC ou botão retorna à relação');
assert.ok(listApp.includes("document.addEventListener('click'"),'controles dentro do modal usam delegação do documento');
assert.ok(listApp.includes("if(a.dataset.action==='add')openAdd()"),'modal aprovado preservado dentro do modal de lista');
assert.ok(html.includes('/x/styles.css'));
assert.ok(html.includes('type="module" src="/x/listas/auth.js'),'Auth começa após aplicação de Listas');
assert.ok(src('x/listas/app.js').includes('TereonXAppActivateAccount'),'uma interface serve à conta e ao modo local');
assert.ok(src('x/listas/app.js').includes('TereonXListIntegration.create'),'armazenamento injetado no serviço de Listas');
assert.ok(html.includes('data-action="home"'),'Início retorna à página principal sem recarregar');
assert.equal(html.includes('id="homeButton"'),false,'sem dois botões Início conflitantes');
assert.equal(src('x/listas/app.js').includes("$('homeButton').addEventListener"),false,'sem listener órfão');
const hub=src('x/laboratorios/index.html');
assert.ok(hub.includes("location.replace('/x/'"),'antiga Central redireciona ao Início único');
const listUi=src('x/listas/app.js');
assert.ok(html.includes('id="homeScreen"')&&html.includes('id="listsScreen"'),'Início independente tem container próprio');
assert.ok(listUi.includes("$('homeScreen').hidden=")&&listUi.includes("$('listsScreen').hidden="),'Listas alterna containers sem reconstruir a Central');
assert.ok(listUi.includes('data.lists.length')&&listUi.includes("$('homeListCount')"),'contagem se atualiza na Central');
assert.ok(html.includes('data-action="create"')&&listUi.includes("$('createDialog').showModal()"),'Criar lista abre modal na mesma página');
