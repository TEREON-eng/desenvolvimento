assert.ok(offsets.every(x=>x>=0)&&offsets.every((x,i)=>i===0||x>offsets[i-1]),'Listas em destaque, depois quatro módulos');
assert.ok(home.includes('href="/x/escola/"'),'Escola é card independente');
assert.ok(src('x/escola/index.html').includes('href="/x/biblioteca/"'),'Biblioteca é sala da Escola');
