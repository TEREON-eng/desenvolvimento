/* Contrato de apresentação: agrupamento por etapa sem perder os lançamentos. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'../..');
const app=fs.readFileSync(path.join(root,'x/listas/app.js'),'utf8');
const quant=fs.readFileSync(path.join(root,'x/listas/quantificacao.js'),'utf8');
const rootWindow={};
const sandbox={window:rootWindow};vm.createContext(sandbox);new vm.Script(quant).runInContext(sandbox);
rootWindow.TereonXCatalog={get(id){return id==='FT_COND-001'?{name:'Condutor isolado'}:null;}};
const esc=value=>String(value).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;');
const start=app.indexOf("  const fmt=n=>Number(n).toLocaleString('pt-BR',{maximumFractionDigits:6});",app.indexOf("}else if(page==='list'){"));
const end=app.indexOf("  if(!l.items.length)html+='<div class=\"empty\">",start);
assert.ok(start>=0&&end>start,'Funções de renderização da lista presentes');
const render=new Function('window','esc',app.slice(start,end)+'return {materialParts,stageMaterialRow,groupCard};')(rootWindow,esc);
const sample=(id,qty,stage,unit='rl200m')=>({id,name:'Condutor isolado de cobre 2,5 mm²',catalogId:'FT_COND-001',values:{'DET-001':'Condutor isolado','DET-002':'Cobre','DET-004':'2,5','DET-011':unit},qty,qtyBasis:'m',unit,stage});
const items=[sample('a',100,'Sala 2'),sample('b',170,'Sala 2')];
const group=rootWindow.TereonXQuant.consolidate(items)[0];
const stage=render.stageMaterialRow(group,items);
assert.equal(group.meters,270);
assert.equal(group.units,2,'rolo de 200 m exige 2 unidades para 270 m');
assert.equal((stage.match(/compact-stage-material-text/g)||[]).length,1,'item técnico aparece uma vez no grupo da etapa');
assert.ok(stage.includes('<strong>Condutor isolado</strong>'),'insumo destacado');
assert.ok(stage.includes('<small>Cobre · 2,5 mm²</small>'),'descrição técnica secundária');
assert.ok(stage.includes('270 m'),'quantidade medida da etapa');
assert.equal((stage.match(/data-edit="/g)||[]).length,2,'dois lançamentos editáveis de origem');
assert.equal((stage.match(/data-duplicate="/g)||[]).length,2);
assert.equal((stage.match(/data-delete="/g)||[]).length,2);
const other=sample('c',40,'Sala 1');
const subgroups=rootWindow.TereonXQuant.consolidate([other]);
assert.equal(subgroups[0].meters,40,'outra etapa permanece independente');
assert.ok(app.includes("const grouped=window.TereonXQuant?.consolidate(entries)||[]"),'agrupamento local por etapa');
const material=render.groupCard(rootWindow.TereonXQuant.consolidate([...items,other])[0],[...items,other]);
assert.ok(material.includes('Sala 2')&&material.includes('Sala 1'),'por insumo continua rastreando etapas');
console.log('Visões compactas por etapa/insumo, identidade técnica, quantidades e ações OK');
